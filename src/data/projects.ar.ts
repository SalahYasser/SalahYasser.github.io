function localize(p: Project): Project {
  const t = ar[p.slug];
  if (!t) throw new Error(`Missing Arabic text for project "${p.slug}"`);
  const { links, screenshots, sections, ...rest } = t;
  return {
    ...p,
    ...rest,
    links: p.links.map((l, i) => ({ ...l, ...links?.[i] })),
    screenshots: p.screenshots.map((s, i) => ({ ...s, ...screenshots?.[i] })),
    sections: p.sections && sections ? sections : p.sections,
  };
}

export const projects: Project[] = projectsEn.map(localize);

const showPending = import.meta.env.PUBLIC_SHOW_PENDING === 'true';
export const visibleProjects = projects.filter((p) => p.approval === 'approved' || showPending);
export const caseStudies = visibleProjects.filter((p) => p.caseStudy && p.sections);
export const compactProjects = visibleProjects.filter((p) => !p.caseStudy);
